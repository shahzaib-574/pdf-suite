import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {PDFDocument} from 'pdf-lib';
import {readFile,mkdir} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
try {
await mkdir("tmp", {recursive:true});
const page=await browser.newPage({viewport:{width:449,height:754},acceptDownloads:true});
await page.addInitScript(()=>{window.showSaveFilePicker=undefined});
const scanWorkers=[];page.on('worker', w=>{if(w.url().includes('scanWorker')) scanWorkers.push(w.url())});
await page.goto('http://127.0.0.1:5173/#/tool/scan');
const images=await page.evaluate(()=>['red','blue'].map(color=>{const c=document.createElement('canvas');c.width=240;c.height=320;const ctx=c.getContext('2d');ctx.fillStyle=color;ctx.fillRect(0,0,240,320);return c.toDataURL().split(',')[1]}));
const payload=images.map((data,i)=>({name:`page-${i}.png`,mimeType:'image/png',buffer:Buffer.from(data,'base64')}));
await page.locator('.scan-cam input[type=file]').setInputFiles(payload);
await page.getByRole('heading',{name:'Crop and Edit',exact:true}).waitFor();
assert.equal(await page.locator('#primary-navigation').count(),0);
assert.equal(await page.locator('.ps-steps').count(),0);
const dimensions=()=>page.locator('.scan-edit__slide').first().locator('img').evaluate(img=>[img.naturalWidth,img.naturalHeight]);
await page.getByRole('button',{name:'Rotate left',exact:true}).click();
assert.deepEqual(await dimensions(),[240,320]);
assert.equal(await page.locator('.ps-scan-editor__image').first().evaluate(el=>el.style.transform),'rotate(-90deg)');
await page.getByRole('button',{name:'Reset',exact:true}).click();
await page.getByRole('button',{name:'Rotate right',exact:true}).click();
assert.deepEqual(await dimensions(),[240,320]);
assert.equal(scanWorkers.length,0);
await page.getByRole('button',{name:'Reset',exact:true}).click();
await page.getByRole('button',{name:'Rotate right',exact:true}).click();
const carousel=page.locator('.scan-edit__carousel');const box=await carousel.boundingBox();
await page.mouse.move(box.x+box.width*.7,box.y+box.height*.5);await page.mouse.down();await page.mouse.move(box.x+box.width*.2,box.y+box.height*.5,{steps:8});await page.mouse.up();
await page.waitForFunction(()=>document.querySelector('[aria-label="Edit page 2"]').getAttribute('aria-current')==='page');
assert.equal(await page.locator('.ps-scan-editor__image').first().evaluate(el=>el.style.transform),'rotate(90deg)');
assert.equal(await page.locator('.ps-scan-editor__image').first().evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
assert.equal(await page.locator('.ps-scan-editor__image').nth(1).evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
await page.getByRole('button',{name:'Add more pages',exact:true}).last().click();
await page.getByLabel('Choose photos').setInputFiles(payload.slice(0,1));
await page.waitForFunction(()=>document.querySelectorAll('.scan-edit__slide img').length===3);
await page.getByRole('button',{name:'Edit page 1',exact:true}).click();
await page.getByRole('button',{name:'Corner 1: use arrow keys to adjust',exact:true}).press('ArrowRight');
await page.getByRole('button',{name:'Rotate right',exact:true}).click();
assert.equal(scanWorkers.length,0);
await page.getByRole('button',{name:'Next',exact:true}).click();
await page.getByRole('textbox',{name:'PDF name'}).fill('Carousel test');
assert.equal(scanWorkers.length,1);
const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Save PDF',exact:true}).click();
const download=await downloadPromise;assert.equal(download.suggestedFilename(),'Carousel test.pdf');
assert.equal((await PDFDocument.load(await readFile(await download.path()))).getPageCount(),3);
await page.goto('http://127.0.0.1:5173/#/tool/scan');await page.locator('.scan-cam input[type=file]').setInputFiles(payload);
await page.getByRole('heading',{name:'Crop and Edit',exact:true}).waitFor();
await page.screenshot({path:'tmp/scan-carousel-449.png'});
for(const width of [320,449,1000]) {await page.setViewportSize({width,height:754});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));const b=await page.locator('.scan-edit__toolbar').boundingBox();assert.ok(b.y+b.height<=755);}
await page.getByRole('button',{name:'Rotate right',exact:true}).click();
const beforeCamera=scanWorkers.length;
await page.getByRole('button',{name:'Return to camera',exact:true}).click();await page.locator('.scan-cam').waitFor();
await page.getByRole('button',{name:'Close camera',exact:true}).click();
assert.equal(await page.locator('.ps-scan-editor__image').first().evaluate(el=>el.style.transform),'rotate(90deg)');
assert.equal(scanWorkers.length,beforeCamera);
console.log('PASS no workers during edits; exactly one worker on Next; carousel drag, add gallery, left/right rotation, reset, crop on Next, named three-page PDF, camera return, 320/449/1000 layouts');
}finally{await browser.close()}
