def draw_table(pdf: canvas.Canvas) -> None:
    width, height = A4
    draw_page_chrome(pdf, 3, "Structured table", A4)
    pdf.setFillColor(INK)
    pdf.setFont("Helvetica-Bold", 23)
    pdf.drawString(40, height - 108, "Sample inventory table")
    draw_wrapped(
        pdf,
        "A ruled table for checking row detection, wrapped cells, numeric alignment, and status labels.",
        40,
        height - 133,
        width - 80,
        font_size=10,
        leading=14,
        color=MUTED,
    )

    rows = [
        ("Fixture cover", "Document", "1", "$0.00", "Ready"),
        ("Quality memo", "Text", "2", "$0.00", "Ready"),
        ("Inventory table", "Table", "3", "$0.00", "Review"),
        ("Two-column guide", "Layout", "4", "$0.00", "Ready"),
        ("Operations summary", "Landscape", "5", "$0.00", "Review"),
        ("Synthetic non-confidential screenshot archive", "Privacy", "0 files", "$0.00", "Private"),
    ]
    headers = ("Item", "Category", "Page", "Cost", "Status")
    x_positions = [40, 230, 342, 400, 476]
    column_widths = [190, 112, 58, 76, 79]
    top = height - 190
    row_height = 49

    pdf.setFillColor(PURPLE)
    pdf.roundRect(40, top - 34, width - 80, 34, 10, fill=1, stroke=0)
    pdf.setFillColor(CARD)
    pdf.setFont("Helvetica-Bold", 9)
    for index, header in enumerate(headers):
        if index in (2, 3):
            pdf.drawRightString(x_positions[index] + column_widths[index] - 10, top - 22, header)
        else:
            pdf.drawString(x_positions[index] + 10, top - 22, header)

    for row_index, row in enumerate(rows):
        row_top = top - 34 - row_index * row_height
        pdf.setFillColor(CARD if row_index % 2 == 0 else HexColor("#FAF9FD"))
        pdf.setStrokeColor(LINE)
        pdf.rect(40, row_top - row_height, width - 80, row_height, fill=1, stroke=1)
        for cell_index, cell in enumerate(row):
            x = x_positions[cell_index]
            pdf.setFillColor(INK if cell_index != 4 else (TEAL if cell in ("Ready", "Private") else PURPLE))
            font_name = "Helvetica-Bold" if cell_index in (0, 4) else "Helvetica"
            font_size = 9.2
            pdf.setFont(font_name, font_size)
            if cell_index in (2, 3):
                pdf.drawRightString(x + column_widths[cell_index] - 10, row_top - 29, cell)
            else:
                cell_lines = wrap_text(cell, font_name, font_size, column_widths[cell_index] - 20)
                baseline = row_top - (22 if len(cell_lines) > 1 else 29)
                for line_index, line in enumerate(cell_lines):
                    pdf.drawString(x + 10, baseline - line_index * 12, line)

    table_bottom = top - 34 - len(rows) * row_height
    pdf.setLineWidth(0.6)
    for separator_x in x_positions[1:]:
        pdf.setStrokeColor(HexColor("#8B79F2"))
        pdf.line(separator_x, top - 34, separator_x, top)
        pdf.setStrokeColor(LINE)
        pdf.line(separator_x, table_bottom, separator_x, top - 34)

    note_y = table_bottom - 80
    pdf.setFillColor(SOFT_TEAL)
    pdf.roundRect(40, note_y, width - 80, 64, 13, fill=1, stroke=0)
    pdf.setFillColor(TEAL)
    pdf.setFont("Helvetica-Bold", 9.5)
    pdf.drawString(56, note_y + 40, "TABLE NOTE")
    draw_wrapped(
        pdf,
        "All values are fictional. The zero cost and generic labels prevent accidental disclosure or misleading commercial claims.",
        56,
        note_y + 22,
        width - 112,
        font_size=9.2,
        leading=13,
    )
    pdf.showPage()


