def draw_landscape(pdf: canvas.Canvas) -> None:
    page_size = landscape(A4)
    pdf.setPageSize(page_size)
    width, height = page_size
    draw_page_chrome(pdf, 5, "Landscape summary", page_size)
    pdf.setFillColor(INK)
    pdf.setFont("Helvetica-Bold", 22)
    pdf.drawString(40, height - 105, "Landscape operations summary")
    pdf.setFillColor(MUTED)
    pdf.setFont("Helvetica", 10)
    pdf.drawString(40, height - 128, "A wide page for mixed-orientation rendering and conversion checks.")

    cards = [
        ("Scan", "Ready", "Camera intake"),
        ("Extract", "Ready", "Text and tables"),
        ("Organize", "Ready", "Reorder and rotate"),
        ("Export", "Review", "PDF and DOCX"),
    ]
    card_width = (width - 104) / 4
    card_y = height - 238
    for index, (label, status, detail) in enumerate(cards):
        x = 40 + index * (card_width + 8)
        pdf.setFillColor(CARD)
        pdf.setStrokeColor(LINE)
        pdf.roundRect(x, card_y, card_width, 82, 14, fill=1, stroke=1)
        pdf.setFillColor(PURPLE)
        pdf.setFont("Helvetica-Bold", 12)
        pdf.drawString(x + 14, card_y + 55, label)
        pdf.setFillColor(TEAL if status == "Ready" else PURPLE)
        pdf.setFont("Helvetica-Bold", 8)
        pdf.drawRightString(x + card_width - 14, card_y + 56, status.upper())
        pdf.setFillColor(MUTED)
        pdf.setFont("Helvetica", 8.7)
        pdf.drawString(x + 14, card_y + 25, detail)

    table_top = card_y - 42
    widths = [180, 120, 115, 125, 125]
    headers = ["Check", "Owner", "Evidence", "Result", "Next action"]
    rows = [
        ["Navigation", "Product", "5 destinations", "Pass", "Keep stable"],
        ["Focus visibility", "Accessibility", "3 px outline", "Pass", "Re-test"],
        ["Store graphics", "Release", "Automated verifier", "Pass", "Upload"],
        ["Android screenshots", "Publisher", "Real device capture", "Pending", "Capture"],
    ]
    x_positions = [40]
    for column_width in widths[:-1]:
        x_positions.append(x_positions[-1] + column_width)

    pdf.setFillColor(PURPLE)
    pdf.roundRect(40, table_top - 31, sum(widths), 31, 9, fill=1, stroke=0)
    pdf.setFillColor(CARD)
    pdf.setFont("Helvetica-Bold", 8.5)
    for index, header in enumerate(headers):
        pdf.drawString(x_positions[index] + 9, table_top - 20, header)

    row_height = 37
    for row_index, row in enumerate(rows):
        row_y = table_top - 31 - (row_index + 1) * row_height
        pdf.setFillColor(CARD if row_index % 2 == 0 else HexColor("#FAF9FD"))
        pdf.setStrokeColor(LINE)
        pdf.rect(40, row_y, sum(widths), row_height, fill=1, stroke=1)
        for cell_index, cell in enumerate(row):
            pdf.setFillColor(TEAL if cell == "Pass" else (PURPLE if cell == "Pending" else INK))
            pdf.setFont("Helvetica-Bold" if cell_index in (0, 3) else "Helvetica", 8.4)
            pdf.drawString(x_positions[cell_index] + 9, row_y + 14, cell)

    pdf.showPage()


def generate(output_path: Path = OUTPUT_PATH) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    pdf = canvas.Canvas(
        str(output_path),
        pagesize=A4,
        # Leave content streams uncompressed so byte-for-byte CI verification
        # does not depend on the runner's zlib implementation.
        pageCompression=0,
        invariant=1,
    )
    pdf.setTitle("Ream Screenshot Fixture")
    pdf.setAuthor("Ream")
    pdf.setSubject("Synthetic non-confidential content for Android store screenshots")
    pdf.setKeywords("Ream, PDF, screenshot, fixture, synthetic")
    draw_cover(pdf)
    draw_memo(pdf)
    draw_table(pdf)
    draw_columns(pdf)
    draw_landscape(pdf)
    pdf.save()
    return output_path


def verify_committed_fixture() -> None:
    if not OUTPUT_PATH.is_file():
        raise SystemExit(f"Committed fixture is missing: {OUTPUT_PATH}")

    with tempfile.TemporaryDirectory(prefix="ream-screenshot-fixture-") as temp_dir:
        candidate = Path(temp_dir) / OUTPUT_PATH.name
        generate(candidate)
        expected_bytes = OUTPUT_PATH.read_bytes()
        candidate_bytes = candidate.read_bytes()

    if candidate_bytes != expected_bytes:
        raise SystemExit(
            "Committed screenshot fixture does not match the deterministic generator. "
            "Regenerate it with this script and review every rendered page."
        )
    print(f"SCREENSHOT_FIXTURE_OK bytes={len(expected_bytes)} path={OUTPUT_PATH}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Regenerate to a temporary path and byte-compare with the committed fixture.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=OUTPUT_PATH,
        help="Output path when generating (defaults to the committed fixture).",
    )
    args = parser.parse_args()

    if args.check:
        verify_committed_fixture()
        return
    print(generate(args.output.resolve()))


if __name__ == "__main__":
    main()
