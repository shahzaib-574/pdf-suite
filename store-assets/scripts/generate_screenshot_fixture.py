OUTPUT_PATH = Path(__file__).resolve().parent.parent / "fixtures" / "ream-screenshot-fixture.pdf"

INK = HexColor("#211D33")
MUTED = HexColor("#716C82")
PURPLE = HexColor("#6652E8")
BLUE = HexColor("#6F86F4")
TEAL = HexColor("#168F84")
SURFACE = HexColor("#F5F3FA")
CARD = HexColor("#FFFFFF")
LINE = HexColor("#DDD8EA")
SOFT_PURPLE = HexColor("#EEEAFE")
SOFT_TEAL = HexColor("#E3F5F2")


def wrap_text(text: str, font_name: str, font_size: float, width: float) -> list[str]:
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        candidate = word if not current else f"{current} {word}"
        if stringWidth(candidate, font_name, font_size) <= width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def draw_wrapped(
    pdf: canvas.Canvas,
    text: str,
    x: float,
    y: float,
    width: float,
    *,
    font_name: str = "Helvetica",
    font_size: float = 10.5,
    leading: float = 15,
    color=INK,
) -> float:
    pdf.setFillColor(color)
    pdf.setFont(font_name, font_size)
    for line in wrap_text(text, font_name, font_size, width):
        pdf.drawString(x, y, line)
        y -= leading
    return y


def draw_page_chrome(
    pdf: canvas.Canvas,
    page_number: int,
    section: str,
    page_size: tuple[float, float],
) -> None:
    width, height = page_size
    pdf.setFillColor(SURFACE)
    pdf.rect(0, 0, width, height, fill=1, stroke=0)
    pdf.setFillColor(PURPLE)
    pdf.roundRect(40, height - 58, 26, 26, 8, fill=1, stroke=0)
    pdf.setFillColor(CARD)
    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawCentredString(53, height - 49, "R")
    pdf.setFillColor(INK)
    pdf.setFont("Helvetica-Bold", 9)
    pdf.drawString(76, height - 43, "REAM SCREENSHOT FIXTURE")
    pdf.setFillColor(MUTED)
    pdf.setFont("Helvetica", 8.5)
    pdf.drawRightString(width - 40, height - 43, section.upper())

    pdf.setStrokeColor(LINE)
    pdf.setLineWidth(0.6)
    pdf.line(40, 35, width - 40, 35)
    pdf.setFillColor(MUTED)
    pdf.setFont("Helvetica", 8)
    pdf.drawString(40, 21, "Synthetic content - safe for product screenshots")
    pdf.drawRightString(width - 40, 21, f"Page {page_number} of 5")


def draw_badge(pdf: canvas.Canvas, text: str, x: float, y: float, width: float) -> None:
    pdf.setFillColor(SOFT_TEAL)
    pdf.roundRect(x, y, width, 24, 12, fill=1, stroke=0)
    pdf.setFillColor(TEAL)
    pdf.setFont("Helvetica-Bold", 8.5)
    pdf.drawCentredString(x + width / 2, y + 8, text)


def draw_bullet(
    pdf: canvas.Canvas,
    text: str,
    x: float,
    y: float,
    width: float,
    *,
    number: int | None = None,
) -> float:
    pdf.setFillColor(PURPLE)
    pdf.circle(x + 6, y + 4, 6, fill=1, stroke=0)
    pdf.setFillColor(CARD)
    pdf.setFont("Helvetica-Bold", 7.5)
    pdf.drawCentredString(x + 6, y + 1.5, str(number) if number is not None else "-")
    return draw_wrapped(pdf, text, x + 20, y + 8, width - 20, font_size=10, leading=14)


def draw_cover(pdf: canvas.Canvas) -> None:
    width, height = A4
    draw_page_chrome(pdf, 1, "Overview", A4)
    draw_badge(pdf, "SYNTHETIC - NON-CONFIDENTIAL - OFFLINE", 40, height - 112, 238)

    pdf.setFillColor(INK)
    pdf.setFont("Helvetica-Bold", 29)
    pdf.drawString(40, height - 166, "A clean document for")
    pdf.setFillColor(PURPLE)
    pdf.drawString(40, height - 201, "real app screenshots")
    draw_wrapped(
        pdf,
        "This deterministic fixture gives Ream realistic text, tables, spacing, and mixed page layouts without exposing personal files.",
        40,
        height - 235,
        440,
        font_size=11.5,
        leading=17,
        color=MUTED,
    )

    card_y = height - 515
    pdf.setFillColor(CARD)
    pdf.setStrokeColor(LINE)
    pdf.setLineWidth(0.7)
    pdf.roundRect(40, card_y, width - 80, 210, 18, fill=1, stroke=1)
    pdf.setFillColor(INK)
    pdf.setFont("Helvetica-Bold", 14)
    pdf.drawString(62, card_y + 177, "Fixture checklist")

    bullets = [
        "Five pages with portrait and landscape orientations.",
        "Headings, paragraphs, numbered steps, and compact callouts.",
        "A ruled data table with numeric and status columns.",
        "Stable sample content that can be regenerated byte-for-byte.",
    ]
    y = card_y + 145
    for index, item in enumerate(bullets, start=1):
        y = draw_bullet(pdf, item, 62, y, width - 124, number=index) - 7

    metric_y = 92
    metric_width = (width - 96) / 3
    for index, (value, label) in enumerate(
        [("5", "sample pages"), ("1", "structured table"), ("0", "personal records")]
    ):
        x = 40 + index * (metric_width + 8)
        pdf.setFillColor(SOFT_PURPLE if index < 2 else SOFT_TEAL)
        pdf.roundRect(x, metric_y, metric_width, 62, 14, fill=1, stroke=0)
        pdf.setFillColor(PURPLE if index < 2 else TEAL)
        pdf.setFont("Helvetica-Bold", 20)
        pdf.drawString(x + 15, metric_y + 30, value)
        pdf.setFont("Helvetica", 8.5)
        pdf.drawString(x + 15, metric_y + 14, label)
    pdf.showPage()


